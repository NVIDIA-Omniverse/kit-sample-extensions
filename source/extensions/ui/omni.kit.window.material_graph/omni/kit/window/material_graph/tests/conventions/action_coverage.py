"""Auditable mapping from user-visible actions to valuable automated tests.

This is deliberately data, not a line-coverage allowlist.  Each entry names the production
surface that owns an action and at least one behavioral test that would fail if the action's
contract regressed.  The convention tests validate the source anchors and test references so
the map cannot silently become stale.
"""

from dataclasses import dataclass


@dataclass(frozen=True)
class ActionCoverage:
    """One user action and the automated evidence covering it."""

    action_id: str
    surface: str
    source: str
    anchor: str
    tests: tuple[str, ...]
    layers: frozenset[str]
    registry_action: str = ""


def _action(
    action_id: str,
    surface: str,
    source: str,
    anchor: str,
    *tests: str,
    layers: tuple[str, ...] = ("controller",),
    registry_action: str = "",
) -> ActionCoverage:
    return ActionCoverage(action_id, surface, source, anchor, tests, frozenset(layers), registry_action)


